#  变量不是盒子 
#
# 很多人学编程的时候，第一课会告诉你：
# “变量就像一个盒子，你把数据装进去”
#
# 这个说法不对。
# 变量不是盒子，变量是贴在盒子上的标签。


# 你写 a = 1 的时候，实际上发生了两件事：
# 1. 先在内存里造一个“盒子”（一块内存区域），里面装上 1
# 2. 造一张标签，上面写着 a，然后把这张标签贴到那个盒子上


# 用代码验证一下
a = 1
b = a
#
# 这里的 b = a 不是“把 a 的值复制一份给 b”
# 是“把 a 那张标签复印一份，贴到同一个盒子上”
#
# 所以 a 和 b 指向的是同一个东西
# 你用 a 去改，b 能看到；你用 b 去改，a 也能看到
#
# 这个区别在“列表”这种可变对象上特别明显
# 但对于整数这种不可变对象，你感觉不到，因为整数不能原地修改
# 不信？往下看


#  变量名可以随便起 
# 规则只有一条：第一个字符不能是数字
# 其他的随便你

a = 1
b = 1
admin = 12
判断 = 12          # 中文也能当变量名！但很少有人这么干
_name = "hello"    # 下划线开头也可以
user1 = "张三"     # 数字结尾可以
# 1user = "李四"   # 数字开头不行，这行注释掉，开了会报错


#  变量可以指向任何东西 
# 变量不仅可以指向数字、字符串、列表
# 还可以指向函数

x = print('admin')
# 这行执行的时候会先运行 print('admin')，然后把返回值（None）赋值给 x
# 所以 x 现在指向的是 None
print(x)   # 输出 None


# 布尔值也可以装进变量
a = True
b = False
# 于是你可以写：
T = True
F = False
# 然后在代码里用 T 和 F 代替 True 和 False
# 有些人觉得这样写代码更短，但更多人觉得直接写 True/False 更清楚
# 这个看个人习惯

a == T   # 相当于 a == True
b == F   # 相当于 b == False


