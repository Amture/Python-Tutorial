# print 是 Python 自带的函数
# 它的活很简单：把你递给它的东西，显示到终端上
# 你把它当成一个喇叭就行，你递什么，它喊什么

print("你好")   # 输出 你好


#  print() 空着写，就是喊一个空行 
#
# 不递给它东西，它就喊一个空行
# 有时候想让输出之间空一行，就写 print()

print("第一行")
print()          # 这里空了一行
print("第二行")


#  能往喇叭里递什么？ 
#
# 啥都行。数字、字符串、变量、表达式、列表、字典、True、False……
# 记住一条就行：
# 加引号，是字符串本身
# 不加引号，是那个东西的值

A = 1
print(A)          # 输出 1，因为 A 指向 1
print("A")        # 输出 A，因为 "A" 就是字符串 A
print(1 + 2)      # 输出 3，先算 1+2 再打印
print([1, 2, 3])  # 输出 [1, 2, 3]


#  print 干完活不留东西 
#
# 这是小白最容易懵的地方，慢慢看
#
# print 负责“显示”，但它自己“不留值”
# 你让它显示完，它拍拍屁股就走了，返回一个 None
#
# 什么叫返回 None？
# 就是：print 干完活，交回来的东西是“空”

D = print(A)
#
# 这行发生了两件事：
# 1. print(A) 先执行，屏幕上显示 1
# 2. print 执行完返回 None，这个 None 被赋给了 D
#
# 所以：
# 屏幕上你看到 1，那是 print 显示出来的
# 但 D 接住的是 None，不是 1
#
# 显示归显示，返回归返回，两码事

print(D)          # 输出 None，因为 D 就是 None


#  单独写变量名，不会自动输出 
#
# 很多小白以为，写个 D 就能看到 D
# 不是的
# 单独写 D，只是“访问一下 D”，不会显示任何东西
# 想看 D，必须用 print(D)

D                 # 这行啥也不输出
print(D)          # 这才输出 None


#  字符串 + 变量，怎么拼？ 
#
# 你想输出“输出为 1”，怎么办？
# 用 f-string
# 在引号前面加个 f，然后在 {} 里写变量或表达式

print(f"输出为 {A}")   # 输出 输出为 1

# f 是啥？
# f 是个前缀，表示这个字符串里的 {} 要替换成变量的值
# 你先记成：f"..." = 带变量的字符串
# 官方叫 formatted string literal，简称 f-string
