#  列表也能比较 
# a = [1, 2] 和 b = [1, 2]
# 内容一样，所以相等

a = [1, 2]
b = [1, 2]
c = ['a', 'b']
d = ['a', 'b', 'c']

if a == b:
    print(456)   # 输出 456，因为 a 和 b 内容一样


#  列表比大小是按顺序比 
# Python 比较两个列表的时候，是从第一个元素开始比较
# 如果第一个元素一样，再比第二个，以此类推
# 这里 c = ['a', 'b']，d = ['a', 'b', 'c']
# 前两个元素一样，但 d 比 c 多一个元素
# 在 Python 里，长度不同的列表比较会先看能否通过元素比出大小
# 比不出来的时候，短的那个算更小
# 
# 所以你写的 c > d 其实没必要深究
# 你只需要知道：列表可以比大小，但规则比较绕，一般不会这么用

if c > d:
    print(123)   # 不输出，因为这里条件不成立


