# 比较运算符：比大小的

print("===== 一、算术运算符 =====")
print()


#  加减乘除 
# 就是字面意思的加减乘除，没啥好说的
print("加减乘除")
print("1 + 1 =", 1 + 1)
print("3 - 2 =", 3 - 2)
print("4 * 5 =", 4 * 5)
print("10 / 4 =", 10 / 4)    # 注意：/ 的结果永远是小数（浮点数）


#  整除 // 
# 只取整数部分，小数点后面的直接扔掉
# 不四舍五入！是直接丢掉
# 比喻：10个苹果分给4个人，每人拿几个完整的？答案是2个
print()
print("整除 //")
print("10 // 4 =", 10 // 4)   # 2
print("10 // 3 =", 10 // 3)   # 3
print("7 // 2 =", 7 // 2)     # 3


#  取模（求余数）% 
# 问的是：还剩几个？
# 10个苹果分给4个人，每人拿2个，剩下几个？剩下2个
print()
print("取模（求余数）%")
print("10 % 4 =", 10 % 4)     # 2
print("10 % 3 =", 10 % 3)     # 1
print("7 % 2 =", 7 % 2)       # 1


#  幂运算 ** 
# 几的几次方
print()
print("幂运算 **")
print("2 ** 3 =", 2 ** 3)     # 2的三次方 = 8
print("3 ** 2 =", 3 ** 2)     # 3的平方 = 9
print("10 ** 2 =", 10 ** 2)   # 10的平方 = 100


#  / 和 // 的区别 
#
# 10 / 4   = 2.5     普通除法，结果是小数
# 10 // 4  = 2       整除除法，只要整数部分
# 10 % 4   = 2       取余数，问还剩几个
#
# 这仨是一个组合：
# 10 ÷ 4 = 2 余 2
# 10 // 4 = 2
# 10 % 4  = 2


print()
print("===== 二、比较运算符 =====")
print()


#  == 和 != 
# == 问：两边相等吗？
# != 问：两边不相等吗？
print("==  等于")
print("1 == 1", 1 == 1)       # True
print("1 == 2", 1 == 2)       # False

print("!=  不等于")
print("1 != 1", 1 != 1)       # False
print("1 != 2", 1 != 2)       # True


#  > < >= <= 
# 大于、小于、大于等于、小于等于
print(">   大于")
print("3 > 2", 3 > 2)         # True
print("2 > 3", 2 > 3)         # False

print("<   小于")
print("2 < 3", 2 < 3)         # True
print("3 < 2", 3 < 2)         # False

print(">=  大于等于")
print("3 >= 3", 3 >= 3)       # True
print("2 >= 3", 2 >= 3)       # False

print("<=  小于等于")
print("3 <= 3", 3 <= 3)       # True
print("4 <= 3", 4 <= 3)       # False


#  比较运算符返回的是布尔值 
# True 就是“成立”，False 就是“不成立”
# 这个 True/False 是可以拿去用的

result = 5 > 3
print("5 > 3 的结果是：", result)   # True
print(type(result))                   # <class 'bool'>


