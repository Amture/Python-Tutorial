# 这个文件讲的是 is 和 is not
# 翻译成人话：这俩标签是不是贴在同一间房子上？


# 之前我们讲过，变量不是盒子，是标签
# 你写 a = [1, 2] 的时候：
#   1. 先在内存里造一个盒子，里面装 [1, 2]
#   2. 在盒子上贴一张标签，叫 a

a = [1, 2]
b = a           # 这里不是复制！是把 a 那张标签复印了一份，贴到同一个盒子上
c = [1, 2]      # 这是重新造了一个新盒子，里面也装 [1, 2]


#  is：问“这俩标签是不是贴在同一间房子上？” 
# 比较的是门牌号（内存地址）
# 好比两个人都姓王，但不一定是同一个人

if a is b:
    print('True')   # a 和 b 是同一间房子（b = a 贴了同一间）
else:
    print('False')

if b is c:
    print('True')
else:
    print('False')  # b 和 c 是两间不同的房子
                    # 虽然里面都装着 [1, 2]，但门牌号不同


#  is not：反过来问 
# “这俩标签是不是贴在不同房子上？”

if a is not b:
    print('False')
else:
    print('True')   # a 和 b 是同一间，所以“a is not b”是假的，走 else

if b is not c:
    print('False')  # b 和 c 是不同房子，所以“b is not c”是真的，走这里
else:
    print('True')


#  重点区分 
#
# ==  ：值相等就行（你们俩是不是都姓王？）
# is  ：必须是同一间房子（你们俩是不是同一个人？）



#  为啥会有这个区别？ 
#
# ==  ：值相等就行
#       你们俩是不是长得一模一样？
#       a = [1, 2] 和 b = [1, 2] → True
#       因为里面装的东西一样
#
# is  ：必须是同一个东西
#       你们俩是不是同一个人？
#       a = [1, 2] 和 b = [1, 2] → False
#       因为虽然长得一样，但它们是两间不同的房子
#
# 看例子：
# a = [1, 2]
# b = [1, 2]
# a == b  → True（值一样）
# a is b  → False（两间不同的房子）
#
# a = [1, 2]
# b = a
# a == b  → True（值一样）
# a is b  → True（同一间房子！）


#  啥时候用 is？ 
#
# 大多数情况你用 == 就够了
# 只有两种场景需要用 is：
#
# 1. 判断是不是 None
#    if x is None:      ← 推荐
#    if x == None:      ← 不推荐，虽然也能跑
#
# 2. 判断两个变量是不是指向同一个对象
#    比如你写代码的时候需要确认“这俩是不是同一个东西”
#    这种场景在日常代码里出现得很少
