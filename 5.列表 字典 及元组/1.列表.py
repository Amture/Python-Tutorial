# 现在说修改元素
# 改值：直接往编号里塞新东西
a = None
a = [1,2,3,4,5]
a[1] = 99
print(a)   # [1, 99, 3, 4, 5]

# 如果你不知道位置，但知道内容，先用 index 查位置再改
a = None
a = [1,2,3,4,5]
位置 = a.index(2)   # 查一下 2 在哪个编号
a[位置] = 99        # 把那个位置改成 99
print(a)   # [1, 99, 3, 4, 5]

# 如果列表里有多个相同的值，index 只返回第一个
a = None
a = [1, 2, 3, 2, 4, 2, 5]
位置 = a.index(2)   # 返回 1（第一个 2 在编号 1）
a[位置] = 99
print(a)   # [1, 99, 3, 2, 4, 2, 5]  只改了第一个

# 如果想改掉所有匹配的，用循环
a = None
a = [1, 2, 3, 2, 4, 2, 5]
for i in range(len(a)):
    if a[i] == 2:
        a[i] = 99
print(a)   # [1, 99, 3, 99, 4, 99, 5]

# 注意：如果值不存在，index 会报错 ValueError
# 所以稳妥写法是先用 in 判断一下
a = None
a = [1,2,3,4,5]
if 99 in a:
    位置 = a.index(99)
    a[位置] = 100
else:
    print("没找到，不改")
# 输出：没找到，不改


# 现在说添加元素
# 添加元素有三个方式
# 1.添加单个元素到列表最后面
a = None
a = [1,2,3,4,5]
a.append(6)
print(a)
# 2.添加元素到指定位置
a.insert(6,7)
print(a)
# 3.添加另一个列表到旧列表最后面
c = [8,9,10]
a.extend(c)
print(a)



# 同时第二个用法也可以添加列表到指定位置
a = None
a = [1,2,3,4,5]
a.insert(1,c)
print(a)
# 但是这样写有一个很严重的错误
# 输出为：[1, [8, 9, 10], 2, 3, 4, 5]
# 可以看到，c列表一整个当成一个元素塞进去了
# 但是，我们通常是想把这些东西切出来
a = None
a = [1, 2, 3, 4, 5]
# 在位置 1 的地方拆开，把 c 摊开放进去
a = a[:1] + c + a[1:]
# 也就是说，创建一个无变量名的列表，从a列表的位置 1 切开，
# 然后把c的每个元素塞进去，再把原来的a列表的位置 1 后面的塞进去，把这个新列表赋值回a
# 什么？你问旧的？
# 旧的放转转回收了（^^）
print(a)


# 现在说删除元素
# 1.删除指定位置
# 两个写法
a = None
a = [1,2,3,4,5]
del a[1]
print(a)


a = None
a = [1,2,3,4,5]
a.pop(1)
print(a)


# 2.删除指定内容
a = None
a = [1,2,3,4,5]
a.remove(1)
print(a)


# 这时候你该问了
# 小A小A，那个指定位置两个有什么区别啊
# 欸~，区别大了。del删了就真没了，这是个直接使用的函数
# 但是pop是参数类型，也就是说，这玩意可以加入变量名
# 换句话说，pop的原理是，取出指定位置的内容，然后在原列表删除这个位置的内容


# 剩下的都是一些其他用法
# in：问“在不在”
a = None
a = [1,2,3,4,5]
print(2 in a)   # True
print(99 in a)  # False

# index：问“在哪儿”
a = None
a = [1,2,3,4,5]
位置 = a.index(3)
print(位置)   # 2

#  count：问“有几个”
a = None
a = [1, 2, 3, 2, 4, 2, 5]
数量 = a.count(2)
print(数量)   # 3

# 排序
# sort：从小到大排（原地改，不造新列表）
a = None
a = [3, 1, 4, 2, 5]
a.sort()
print(a)   # [1, 2, 3, 4, 5]

# reverse：倒过来排（原地改）
a = None
a = [1, 2, 3, 4, 5]
a.reverse()
print(a)   # [5, 4, 3, 2, 1]

# 这里是复制
# b = a：贴标签，a和b指向同一个列表（改一个另一个也跟着变）
a = [1,2,3,4,5]
b = a
a.append(6)
print(b)   # [1,2,3,4,5,6]  b也跟着变了

# b = a.copy()：造一个内容一样的新列表（两个独立，互不影响）
a = [1,2,3,4,5]
b = a.copy()
a.append(6)
print(a)   # [1,2,3,4,5,6]
print(b)   # [1,2,3,4,5]  b没变，因为a和b各自独立

# b = a[:]：切片复制，和copy效果一样
a = [1,2,3,4,5]
b = a[:]
a.append(6)
print(a)   # [1,2,3,4,5,6]
print(b)   # [1,2,3,4,5]


# 清空
# a = []：换一个新列表（如果b也指着旧列表，b不受影响）
a = [1,2,3,4,5]
b = a
a = []
print(a)   # []
print(b)   # [1,2,3,4,5]  b还指着旧列表

# a.clear()：把原列表掏空（b也看到空的）
a = [1,2,3,4,5]
b = a
a.clear()
print(a)   # []
print(b)   # []  b也跟着空了


# 最后说一个重要的点：列表能套列表
# 你之前已经见过 [1, [8,9,10], 2,3,4,5] 了
a = [1, [8, 9, 10], 2, 3, 4, 5]
# 怎么拿里面的 9？
print(a[1][1])   # 第一个 [1] 取到子列表，第二个 [1] 取子列表里的第二个元素
# 输出：9

# 怎么改里面的 9 改成 99？
a[1][1] = 99
print(a)   # [1, [8, 99, 10], 2, 3, 4, 5]

# 怎么往子列表里加东西？
a[1].append(11)
print(a)   # [1, [8, 99, 10, 11], 2, 3, 4, 5]

# 怎么删子列表里的东西？
a[1].pop(0)
print(a)   # [1, [99, 10, 11], 2, 3, 4, 5]

