"""
    我们这个讲的是字典
"""

# 字典长这样
a = {"元素一": "1", "元素二": "2", "元素三": "3"}

"""
    这就是字典
    
    字典用名字（键）找东西，不是用编号（0、1、2）
    写法：用花括号 {} 包起来，里面是 "键": "值" 成对出现，中间用冒号
"""


# 现在说取值
# 用 []，里面写键名，不是写编号
a = {"元素一": "1", "元素二": "2", "元素三": "3"}
print(a["元素一"])   # 输出：1
print(a["元素二"])   # 输出：2


# 现在说改值
# 直接赋值
a = {"元素一": "1", "元素二": "2"}
a["元素一"] = "壹"
print(a)   # {"元素一": "壹", "元素二": "2"}


# 现在说添加
# 键不存在的时候赋值，就是添加
a = {"元素一": "1", "元素二": "2"}
a["元素三"] = "3"
print(a)   # {"元素一": "1", "元素二": "2", "元素三": "3"}


# 现在说删除
# 1. del：直接删
a = {"元素一": "1", "元素二": "2", "元素三": "3"}
del a["元素二"]
print(a)   # {"元素一": "1", "元素三": "3"}

# 2. pop：删掉并取出值
a = {"元素一": "1", "元素二": "2", "元素三": "3"}
x = a.pop("元素一")
print(a)   # {"元素二": "2", "元素三": "3"}
print(x)   # 1  被删掉的值

# 3. clear：全清空
a = {"元素一": "1", "元素二": "2"}
a.clear()
print(a)   # {}


# 现在说安全取值
# get：找不到键的时候不报错，返回 None（或者你自己指定的默认值）
a = {"元素一": "1", "元素二": "2"}
print(a.get("元素一"))        # 1
print(a.get("元素三"))        # None（不会报错）
print(a.get("元素三", "没有")) # 没有（找不到就返回你给的这个值）


# 现在说查找
# in：问"这个键在不在"
a = {"元素一": "1", "元素二": "2"}
print("元素一" in a)   # True
print("元素三" in a)   # False


# 现在说遍历
# 把东西一个一个拿出来
a = {"元素一": "1", "元素二": "2", "元素三": "3"}

# 只拿键
for i in a:
    print(i)   # 元素一 元素二 元素三

# 只拿值
for i in a.values():
    print(i)   # 1 2 3

# 键和值一起拿
for i, j in a.items():
    print(i, j)   # 元素一 1  元素二 2  元素三 3


# 现在说合并
# update：把另一个字典的所有内容加进来
a = {"元素一": "1", "元素二": "2"}
b = {"元素三": "3", "元素四": "4"}
a.update(b)
print(a)   # {"元素一": "1", "元素二": "2", "元素三": "3", "元素四": "4"}

# 注意：如果有相同的键，b 会覆盖 a
a = {"元素一": "1", "元素二": "2"}
b = {"元素二": "贰", "元素三": "3"}
a.update(b)
print(a)   # {"元素一": "1", "元素二": "贰", "元素三": "3"}


# 现在说复制
# copy：造一个内容一样的新字典，各自独立
a = {"元素一": "1", "元素二": "2"}
b = a          # 贴标签，改一个另一个也跟着变
c = a.copy()   # 造新的，互不影响
a["元素一"] = "壹"
print(b)   # {"元素一": "壹", "元素二": "2"}  跟着变了
print(c)   # {"元素一": "1", "元素二": "2"}   没变


# 现在说嵌套
# 字典里面可以套字典，也可以套列表
a = {
    "元素一": "1",
    "元素二": ["一", "二", "三"],
    "元素三": {
        "子元素一": "A",
        "子元素二": "B"
    }
}
print(a["元素二"][1])        # 二（先拿列表，再拿编号1）
print(a["元素三"]["子元素二"]) # B（先拿字典，再拿键）


# 键必须是"不可变"的类型
# 数字、字符串、元组可以当键
# 列表不能当键（因为列表可变）
# 字典也不能当键（因为字典可变）

# 这是可以的（元组当键）
a = {("x", "y"): 100}
print(a[("x", "y")])   # 100

# 这是不行的（列表当键会报错）
# a = {[1, 2]: 100}   # TypeError: unhashable type: 'list'