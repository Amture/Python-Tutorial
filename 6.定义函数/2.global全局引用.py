# 前面定义说到了 def 可以把命令打包成批处理
# 那么问题来了：函数里面动的东西，跟外面有什么关系？
# 写个例子先


a = 100  # 外面定义了个变量 a，说好是 100

def change():
    a = 200  # 这里面也写了一个 a = 200
    print("函数里面的 a 是：", a)
change()
print("外面的 a 是：", a)   # 你猜这个输出是 100 还是 200？

#     运行一下你就会发现
#     外面的 a 还是 100！！！！
#     明明在函数里面写了 a = 200，为什么没改掉外面的？
#     因为 —— 函数里面的 a = 200，是在函数内部“新建”了一个局部变量 a
#     它跟外面那个 a，虽然名字一样，但不是同一个东西
#     就跟你在一楼叫“小王”，二楼也叫“小王”，但不是同一个人一样
#     这个设计是为了防止函数内部乱改外面的东西
#     相当于一个“隔离墙”


# 那如果我确实想改外面的那个 a 呢？
# 用 global 声明一下
b = 100  # 外面的 b
def change_global():
    global b   # 这行就是声明：我要动外面那个 b
    b = 200
    print("函数里面的 b 是：", b)
change_global()
print("外面的 b 是：", b)   # 这次输出就是 200 了！！


#     总结一下：
#     如果你在函数内部写了 变量名 = 值（就是有等号赋值）
#     那么默认情况下，这个变量是函数内部新建的（局部变量）
#     外面的同名变量不会被影响
#
#     如果你真的想改外面的那个全局变量
#     就必须在函数里面第一句写上 global 变量名
#     告诉 Python：“我要动外面的那个，不是在屋里新建一个”


# 还有一个容易踩的坑，看这个：

c = 1
def test():
    global c      # 把这一行注释掉，再跑一下就知道了
    c += 1
    print(c)
test()
print(c)

#     如果没有 global
#     执行到 c += 1 的时候，Python 会认为：
#     “左边是 c = 右边是 c + 1，你又要给 c 赋值，那 c 就是局部变量”
#     但是右边的 c 还没定义呢（因为局部还没有）
#     所以会报错：UnboundLocalError
#     也就是说：
#     如果你要在函数内部【修改】全局变量的值（特别是 +=、-= 这种）
#     必须写 global
#     如果你只是读一下（比如 print(c)）
#     不用写 global，它自动会往外找
